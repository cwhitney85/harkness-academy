<?php

namespace App\Assessment;

/**
 * What a quiz is for (spec 6.1).
 *
 * All four kinds are the same document with different scope, which is what
 * lets one `quizzes` table and one `json/quiz.v1` schema serve them (2.3.2:
 * "one schema, three consumers").
 *
 * **Package 5 writes only `Checkpoint` and `Homework`** -- the two the lesson
 * engine produces (5.2.1, 5.4.1). `Final` and `Refresher` are named here
 * because the enum is the table's vocabulary and a half-listed vocabulary
 * invites a second one; package 6.1's service is what will write them
 * (ledger D12).
 */
enum QuizKind: string
{
    /** Closes one section of a lesson (spec 5.2.1). Informs, never gates. */
    case Checkpoint = 'checkpoint';

    /** Follows a completed lesson (spec 6.2), generated by 5.4.1's chain. */
    case Homework = 'homework';

    /** Gates course completion (spec 6.3). */
    case Final = 'final';

    /** Draws on recorded knowledge after the fact (spec 6.4). */
    case Refresher = 'refresher';

    /**
     * Whether this kind belongs to one section rather than a whole scope.
     *
     * The one kind whose `quizzes.section_index` is set.
     */
    public function isSectionScoped(): bool
    {
        return $this === self::Checkpoint;
    }
}
