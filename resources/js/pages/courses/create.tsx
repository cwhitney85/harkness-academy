import { Head, router, useForm } from '@inertiajs/react';
import { useState } from 'react';

import PipelineShell from '@/components/pipeline-shell';
import { Button } from '@/components/ui/button';
import {
    Tooltip,
    TooltipContent,
    TooltipTrigger,
} from '@/components/ui/tooltip';
import InputError from '@/components/input-error';

/**
 * Screen S2 — starting a course (spec 8.7.1, 8.7.6).
 *
 * One form, two doors, because 4.1 made picking a preset and typing a name the
 * same act: both resolve to the same slug, and a screen with two separate
 * flows would be describing a difference the engine does not have. The catalog
 * is offered first because it is a suggestion; the free-text field sits under
 * it under the same module, which is where the shared slug comes from.
 *
 * Skill level is asked here and never framed as a price (4.5.6): 101 is longer
 * than 301, and the copy says so rather than letting "Introductory" read as
 * "less".
 */

type Subtopic = { id: number; slug: string; title: string };
type Module = { slug: string; title: string; subtopics: Subtopic[] };
type Level = { value: number; title: string };

/** D7b's question, asked before another attempt is created (8.7.6). */
type Resumable = {
    subtopic_title: string;
    level: string;
    /** What starting from scratch would make the new course. */
    next_attempt: number;
    /** Every attempt that can be picked back up, newest first (16.4.2). */
    attempts: {
        course_id: number;
        attempt: number;
        standing: string;
        set_aside_on: string | null;
        resume_url: string;
    }[];
};

/**
 * A typed subtopic the scope check turned away (spec 4.9.6, ledger D42).
 *
 * Every word of it is generated by the app from the verdict and the two
 * module titles. The model's own sentence is stored and never sent here: the
 * probes that produced these verdicts also produced fluent, confident and
 * wrong explanations of them.
 */
type Refused = {
    /** Exactly what was submitted, so the notice can tell it is still there. */
    typed: string;
    title: string;
    headline: string;
    message: string;
    note: string | null;
    start_under: { module_slug: string; module_title: string } | null;
};

/** The subtopic's one open slot is taken — the double tap and the second tab. */
type Occupied = {
    course_id: number;
    subtopic_title: string;
    level: string;
    continue_url: string;
};

/**
 * What each level means, in pedagogy. Never in money: the plan decides
 * economics and skill level decides nothing about it (spec 4.5.6).
 */
const LEVEL_NOTES: Record<number, string> = {
    101: 'Starting from nothing. The longest of the three — beginners need the most scaffolding.',
    201: 'You know the ground and want to be fluent on it.',
    301: 'You are confident, and want the parts that are actually hard.',
};

export default function CreateCourse({
    modules,
    levels,
    resumable,
    occupied,
    refused,
}: {
    modules: Module[];
    levels: Level[];
    resumable: Resumable | null;
    occupied: Occupied | null;
    refused: Refused | null;
}) {
    const [module, setModule] = useState<Module | null>(null);

    const form = useForm({
        source: 'catalog',
        module_slug: '',
        subtopic_id: null as number | null,
        name: '',
        level: 101,
        start_over: false as boolean,
    });

    const chosen = module?.subtopics.find(
        (subtopic) => subtopic.id === form.data.subtopic_id,
    );

    const ready =
        module !== null &&
        (form.data.subtopic_id !== null || form.data.name.trim() !== '');

    /**
     * The refusal is about one typed name, so it stands only while that name
     * is still in the field — which is what makes "Pick something else" a
     * matter of clearing it rather than a piece of dismissal state. The visit
     * back from `store` preserves this component (ledger D28), so state that
     * outlived its own subject would sit there through the next attempt.
     */
    const refusal =
        refused && form.data.name.trim() === refused.typed.trim()
            ? refused
            : null;

    function submit(startOver = false) {
        form.transform((data) => ({
            ...data,
            source: data.subtopic_id === null ? 'free_text' : 'catalog',
            start_over: startOver,
        }));

        form.post('/courses', { preserveScroll: true });
    }

    /** The same subtopic, one submission, under the module that will take it. */
    function startUnder(target: Module) {
        setModule(target);
        form.setData((data) => ({
            ...data,
            module_slug: target.slug,
            subtopic_id: null,
        }));
        form.transform((data) => ({
            ...data,
            source: 'free_text',
            subtopic_id: null,
            module_slug: target.slug,
            start_over: false,
        }));

        form.post('/courses', { preserveScroll: true });
    }

    return (
        <PipelineShell step="start">
            <Head title="Start a course" />

            <div className="measure py-8 sm:py-12">
                <h1 className="display text-[38px] leading-[1.07] sm:text-[43px]">
                    Start a course
                </h1>
                <p className="mt-4 mb-9">
                    Pick a subject and say how deep you want to go. Two short
                    conversations follow — what you already know, and what you
                    want out of this — and a syllabus is drawn up from them for
                    you to approve.
                </p>

                {resumable && (
                    <CarryOnOrStartOver
                        question={resumable}
                        onStartOver={() => submit(true)}
                        disabled={form.processing}
                    />
                )}

                {occupied && <AlreadyOpen course={occupied} />}

                {refusal && (
                    <Refusal
                        refused={refusal}
                        onStartUnder={(slug) => {
                            const target = modules.find(
                                (candidate) => candidate.slug === slug,
                            );

                            if (target) {
                                startUnder(target);
                            }
                        }}
                        onPickSomethingElse={() =>
                            form.setData((data) => ({ ...data, name: '' }))
                        }
                        disabled={form.processing}
                    />
                )}

                <Field label="Choose a subject">
                    <div className="flex flex-wrap gap-2">
                        {modules.map((candidate) => (
                            <button
                                key={candidate.slug}
                                type="button"
                                onClick={() => {
                                    setModule(candidate);
                                    form.setData((data) => ({
                                        ...data,
                                        module_slug: candidate.slug,
                                        subtopic_id: null,
                                        name: '',
                                    }));
                                }}
                                className={[
                                    'flex h-11 items-center border px-4 text-[15px] focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brass',
                                    candidate.slug === module?.slug
                                        ? 'border-wine bg-wine text-surface'
                                        : 'border-hairline bg-surface hover:border-brass',
                                ].join(' ')}
                            >
                                {candidate.title}
                            </button>
                        ))}
                    </div>
                </Field>

                {module && (
                    <>
                        <Field label={`In ${module.title}`}>
                            <ul className="border-t border-hairline">
                                {module.subtopics.map((subtopic) => (
                                    <li key={subtopic.id}>
                                        <button
                                            type="button"
                                            onClick={() =>
                                                form.setData((data) => ({
                                                    ...data,
                                                    subtopic_id: subtopic.id,
                                                    name: '',
                                                }))
                                            }
                                            className={[
                                                'flex min-h-11 w-full items-center gap-3 border-b border-hairline px-3 text-left text-[17px] focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-brass',
                                                subtopic.id === chosen?.id
                                                    ? 'bg-surface'
                                                    : 'hover:bg-surface',
                                            ].join(' ')}
                                        >
                                            <span
                                                className={[
                                                    'h-3.5 w-[3px] flex-none',
                                                    subtopic.id === chosen?.id
                                                        ? 'bg-wine'
                                                        : 'bg-transparent',
                                                ].join(' ')}
                                            />
                                            {subtopic.title}
                                        </button>
                                    </li>
                                ))}
                            </ul>

                            <label className="mt-5 block">
                                <span className="label flex items-center gap-1.5">
                                    Or name it yourself
                                    <FreeTextHint module={module.title} />
                                </span>
                                <input
                                    type="text"
                                    value={form.data.name}
                                    maxLength={120}
                                    placeholder={`Anything else under ${module.title}…`}
                                    onChange={(event) =>
                                        form.setData((data) => ({
                                            ...data,
                                            name: event.target.value,
                                            subtopic_id: null,
                                        }))
                                    }
                                    className="mt-2 h-11 w-full border border-hairline bg-surface px-3.5 text-[17px] placeholder:text-muted-ink focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-brass"
                                />
                                <InputError message={form.errors.name} />
                            </label>
                        </Field>

                        <Field label="How deep">
                            <div className="flex flex-col gap-2">
                                {levels.map((level) => (
                                    <button
                                        key={level.value}
                                        type="button"
                                        onClick={() =>
                                            form.setData('level', level.value)
                                        }
                                        className={[
                                            'flex min-h-11 w-full flex-col items-start gap-0.5 border px-4 py-2.5 text-left focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brass',
                                            level.value === form.data.level
                                                ? 'border-wine bg-surface'
                                                : 'border-hairline hover:border-brass',
                                        ].join(' ')}
                                    >
                                        <span className="text-[17px]">
                                            {level.title}{' '}
                                            <span className="text-muted-ink">
                                                · {level.value}
                                            </span>
                                        </span>
                                        <span className="text-[15px] leading-snug text-muted-ink">
                                            {LEVEL_NOTES[level.value]}
                                        </span>
                                    </button>
                                ))}
                            </div>
                        </Field>
                    </>
                )}

                <InputError message={form.errors.subtopic_id} />
                <InputError message={form.errors.module_slug} />

                <div className="mt-10 flex items-center gap-5">
                    <Button
                        size="action"
                        disabled={!ready || form.processing}
                        onClick={() => submit(false)}
                    >
                        Begin
                    </Button>
                    <span className="label">
                        {chosen
                            ? `${chosen.title} · ${form.data.level}`
                            : form.data.name.trim()
                              ? `${form.data.name.trim()} · ${form.data.level}`
                              : 'Pick a subject to begin'}
                    </span>
                </div>
            </div>
        </PipelineShell>
    );
}

/**
 * What the scope check will do with what is typed here (spec 4.9).
 *
 * The check is invisible until it refuses, and a student who has just been
 * turned away should have been told beforehand that they could be. It hangs
 * off the label rather than sitting under the field because the catalog above
 * is what most students want, and a paragraph of caveat under the input reads
 * as a warning about the whole screen.
 *
 * Opens on click as well as on hover and focus: hover is not a thing on a
 * phone, and this is a PWA.
 */
function FreeTextHint({ module }: { module: string }) {
    const [open, setOpen] = useState(false);

    return (
        <Tooltip open={open} onOpenChange={setOpen}>
            <TooltipTrigger
                type="button"
                aria-label="About naming your own topic"
                onClick={(event) => {
                    // The trigger sits inside the field's own <label>, so
                    // without this a tap lands on the input and raises the
                    // keyboard over the thing it just opened.
                    event.preventDefault();
                    setOpen((shown) => !shown);
                }}
                className="flex size-[18px] items-center justify-center rounded-full border border-hairline text-[11px] text-muted-ink focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brass"
            >
                ?
            </TooltipTrigger>
            <TooltipContent
                side="top"
                className="max-w-xs rounded-none px-3 py-2 text-[13px] leading-snug"
            >
                Pick any topic under {module} you don't see listed here. A topic
                that turns out to belong to another subject or is not covered by
                Harkness Academy is turned away. This is experimental and could
                produce odd results if it does not adhere to the subject.
            </TooltipContent>
        </Tooltip>
    );
}

/** A label, a rule, and whatever it introduces. */
function Field({
    label,
    children,
}: {
    label: string;
    children: React.ReactNode;
}) {
    return (
        <section className="mt-8">
            <h2 className="label border-b border-brass/50 pb-1.5 text-brass">
                {label}
            </h2>
            <div className="mt-4">{children}</div>
        </section>
    );
}

/**
 * D7b's question, in D7b's words (spec 8.7.6).
 *
 * Asked instead of creating another course, because a new attempt cannot be
 * merged back into an old one — and starting over is deliberately still on
 * offer, because sometimes that is what the student wants. With more than one
 * attempt set aside it asks which to continue (16.4.2, ledger D64).
 */
function CarryOnOrStartOver({
    question,
    onStartOver,
    disabled,
}: {
    question: Resumable;
    onStartOver: () => void;
    disabled: boolean;
}) {
    const [only] = question.attempts;
    const several = question.attempts.length > 1;

    const resume = (url: string) =>
        router.post(url, {}, { preserveScroll: true });

    return (
        <aside className="mb-8 border border-t-[3px] border-hairline border-t-wine bg-surface px-5 py-5 sm:px-6">
            <h2 className="label text-wine">You have been here before</h2>
            {several ? (
                <p className="mt-3">
                    You set aside {question.subtopic_title} at the{' '}
                    {question.level} level {question.attempts.length} times.
                    Which would you like to continue, or start from scratch?
                </p>
            ) : (
                <p className="mt-3">
                    You set aside {question.subtopic_title} at the{' '}
                    {question.level} level
                    {only.set_aside_on ? ` on ${only.set_aside_on}` : ''}. Pick
                    up where you left off, or start from scratch?
                </p>
            )}
            {several && (
                <ul className="mt-5 divide-y divide-hairline border-y border-hairline">
                    {question.attempts.map((attempt) => (
                        <li
                            key={attempt.course_id}
                            className="flex flex-wrap items-center justify-between gap-3 py-3"
                        >
                            <div>
                                <p>Attempt {attempt.attempt}</p>
                                <p className="label">
                                    {attempt.standing}
                                    {attempt.set_aside_on
                                        ? ` · set aside on ${attempt.set_aside_on}`
                                        : ''}
                                </p>
                            </div>
                            <Button
                                size="action"
                                disabled={disabled}
                                onClick={() => resume(attempt.resume_url)}
                            >
                                Continue attempt {attempt.attempt}
                            </Button>
                        </li>
                    ))}
                </ul>
            )}
            <div className="mt-5 flex flex-wrap items-center gap-3">
                {!several && (
                    <Button
                        size="action"
                        disabled={disabled}
                        onClick={() => resume(only.resume_url)}
                    >
                        Pick up where I left off
                    </Button>
                )}
                <Button
                    size="action"
                    variant="outline"
                    disabled={disabled}
                    onClick={onStartOver}
                >
                    Start from scratch
                </Button>
            </div>
            <p className="label mt-4">
                Starting over keeps the old {several ? 'courses' : 'course'};
                the new one is attempt {question.next_attempt}.
            </p>
        </aside>
    );
}

/**
 * The scope refusal, and the one way out of it there is (spec 4.9.6).
 *
 * Two buttons and no override. An override would make every wrong verdict a
 * one-tap annoyance rather than a dead end — and would make the refusal
 * advisory, which is the non-blocking flag D42 rejected one screen earlier.
 */
function Refusal({
    refused,
    onStartUnder,
    onPickSomethingElse,
    disabled,
}: {
    refused: Refused;
    onStartUnder: (moduleSlug: string) => void;
    onPickSomethingElse: () => void;
    disabled: boolean;
}) {
    return (
        <aside className="mb-8 border border-t-[3px] border-hairline border-t-wine bg-surface px-5 py-5 sm:px-6">
            <h2 className="label text-wine">{refused.headline}</h2>
            <p className="mt-3">{refused.message}</p>
            {refused.note && <p className="label mt-4">{refused.note}</p>}
            <div className="mt-5 flex flex-wrap items-center gap-3">
                {refused.start_under && (
                    <Button
                        size="action"
                        disabled={disabled}
                        onClick={() =>
                            onStartUnder(refused.start_under!.module_slug)
                        }
                    >
                        Start {refused.title} under{' '}
                        {refused.start_under.module_title}
                    </Button>
                )}
                <Button
                    size="action"
                    variant="outline"
                    disabled={disabled}
                    onClick={onPickSomethingElse}
                >
                    Pick something else
                </Button>
            </div>
        </aside>
    );
}

/** The subtopic's one open slot is already taken (8.6). */
function AlreadyOpen({ course }: { course: Occupied }) {
    return (
        <aside className="mb-8 border border-t-[3px] border-hairline border-t-brass bg-surface px-5 py-5 sm:px-6">
            <h2 className="label text-brass">Already underway</h2>
            <p className="mt-3">
                {course.subtopic_title} at the {course.level} level is already
                open. One course at a time in a subject, so that both are not
                writing down what you know at once.
            </p>
            <div className="mt-5">
                <Button
                    size="action"
                    onClick={() => router.visit(course.continue_url)}
                >
                    Carry on with it
                </Button>
            </div>
        </aside>
    );
}
